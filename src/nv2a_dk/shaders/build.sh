#!/usr/bin/env bash
# Compile the deko3d ubershaders (nv2a_vs.glsl, nv2a_fs.glsl) with uam and
# write them into ../nv2a_dk_shaders.h as byte arrays, so the NRO carries
# them and nothing is compiled on the console.
#
# The header is committed: a Switch build needs no uam. Run this after
# changing a shader:
#
#   UAM=/path/to/uam bash xboxrecomp/src/nv2a_dk/shaders/build.sh
#
# uam: https://github.com/devkitPro/uam (devkitPro also packages it).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UAM="${UAM:-$(command -v uam || echo /opt/devkitpro/tools/bin/uam)}"
[ -x "$UAM" ] || { echo "error: uam not found (set UAM=...)" >&2; exit 1; }
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

"$UAM" -s vert -o "$TMP/vs.dksh" "$HERE/nv2a_vs.glsl"
"$UAM" -s frag -o "$TMP/fs.dksh" "$HERE/nv2a_fs.glsl"
"$UAM" -s vert -o "$TMP/vsf.dksh" "$HERE/nv2a_vs_fixed.glsl"
# The texgen build: the same source with NV2A_TEXGEN 1 after #version.
sed '1a #define NV2A_TEXGEN 1' "$HERE/nv2a_vs_fixed.glsl" > "$TMP/vs_fixed_tg.glsl"
"$UAM" -s vert -o "$TMP/vsftg.dksh" "$TMP/vs_fixed_tg.glsl"

python3 - "$TMP/vs.dksh" "$TMP/fs.dksh" "$TMP/vsf.dksh" "$TMP/vsftg.dksh" "$HERE/../nv2a_dk_shaders.h" <<'EOF'
import sys

def arr(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return ("static const uint8_t %s[%d] __attribute__((aligned(256))) = {\n%s\n};\n"
            % (name, len(data), "\n".join(lines)))

vs = open(sys.argv[1], "rb").read()
fs = open(sys.argv[2], "rb").read()
vsf = open(sys.argv[3], "rb").read()
vsftg = open(sys.argv[4], "rb").read()
with open(sys.argv[5], "w") as out:
    out.write("/* Generated by shaders/build.sh from nv2a_vs.glsl, nv2a_fs.glsl and"
              " nv2a_vs_fixed.glsl (uam). Do not edit. */\n")
    out.write("#ifndef NV2A_DK_SHADERS_H\n#define NV2A_DK_SHADERS_H\n#include <stdint.h>\n\n")
    out.write(arr("s_dksh_vs", vs))
    out.write("\n")
    out.write(arr("s_dksh_fs", fs))
    out.write("\n")
    out.write(arr("s_dksh_vs_fixed", vsf))
    out.write("\n")
    out.write(arr("s_dksh_vs_fixed_tg", vsftg))
    out.write("\n#endif\n")
print("wrote %s: vertex %d, fragment %d, fixed vertex %d (texgen %d) bytes"
      % (sys.argv[5], len(vs), len(fs), len(vsf), len(vsftg)))
EOF
